/** HTTP smoke checks against your running PRODUCTION server; no browser simulation. */
import assert from 'node:assert/strict';
const base = new URL(process.argv[2] || 'http://localhost:3000');
try {
  const swResponse = await fetch(new URL('/sw.js', base), { cache: 'no-store' });
  assert.equal(swResponse.status, 200, '/sw.js must be present');
  assert.match(swResponse.headers.get('content-type') || '', /javascript/, '/sw.js must have a JavaScript MIME type');
  const sw = await swResponse.text();
  const match = /^const BUILD = (\{.*\});$/m.exec(sw);
  assert.ok(match, 'Worker must be generated by scripts/build-pwa.mjs');
  const build = JSON.parse(match[1]);
  assert.ok(build.assets.some(a => a.url.startsWith('/_next/static/')), 'Next.js chunks must be precached');
  for (const item of build.assets) {
    const response = await fetch(new URL(item.url, base));
    assert.ok(response.ok && !response.redirected, `${item.url}: ${response.status} or unexpected redirect`);
    const type = response.headers.get('content-type') || '';
    if (item.url !== '/' && !item.url.endsWith('.html')) assert.ok(!type.includes('text/html'), `${item.url}: HTML fallback instead of an asset`);
    await response.arrayBuffer();
  }
  const manifest = await (await fetch(new URL('/manifest.webmanifest', base))).json();
  assert.equal(manifest.orientation, 'landscape');
  assert.equal(manifest.display, 'standalone');
  assert.equal(manifest.start_url, '/');
  assert.ok(manifest.icons.some(i => i.sizes === '192x192'));
  assert.ok(manifest.icons.some(i => i.sizes === '512x512'));
  assert.ok(manifest.icons.some(i => i.purpose === 'maskable'));
  console.log(`PASS: ${build.assets.length} offline URLs and the landscape PWA manifest are reachable.`);
  console.log('Still required: open in a real browser, wait for Offline ready, disconnect, close/reopen, and complete the six words.');
} catch (error) { console.error('PWA check failed:', error.message); console.error('Start the production server with npm run start first.'); process.exitCode = 1; }
